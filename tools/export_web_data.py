"""Export data and reference values from the Python model for the web app.

Usage
-----
    python tools/export_web_data.py

Writes
------
    docs/js/data.js          experiments, reference machines and published values
    docs/tests/vectors.json  reference values used to test the JavaScript port
"""

from __future__ import annotations

import dataclasses
import json
import math
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import lawson as lw  # noqa: E402
from lawson import reactor  # noqa: E402
from lawson.experiments import load_experiments  # noqa: E402

DOCS = ROOT / "docs"


def finite(value):
    """JSON-safe number: infinities and NaN become strings."""
    if isinstance(value, float):
        if math.isinf(value):
            return "inf" if value > 0 else "-inf"
        if math.isnan(value):
            return "nan"
    return value


# --- Design parameters of existing and proposed tokamaks -----------------------------------
# Creely et al., J. Plasma Phys. 86, 865860502 (2020), Table 1:
# name, R0 (m), a (m), B0 (T), Ip (MA), separatrix elongation, separatrix triangularity,
# maximum auxiliary heating power (MW).
MACHINES = [
    ("SPARC", 1.85, 0.57, 12.2, 8.7, 1.97, 0.54, 25),
    ("Alcator C-Mod", 0.67, 0.21, 8.0, 2.0, 1.8, 0.40, 6),
    ("ASDEX Upgrade", 1.65, 0.50, 3.9, 1.6, 1.6, 0.50, 30),
    ("DIII-D", 1.66, 0.67, 2.2, 2.0, 2.01, 0.75, 27),
    ("EAST", 1.70, 0.40, 3.5, 1.0, 2.0, 0.60, 28),
    ("KSTAR", 1.80, 0.50, 3.5, 2.0, 2.0, 0.80, 16),
    ("ITER", 6.2, 2.0, 5.3, 15.0, 1.85, 0.48, 73),
]


def experiments_payload():
    return [
        {
            "project": e.project,
            "concept": e.concept,
            "category": e.category,
            "date": e.date,
            "shot": e.shot,
            "projected": e.projected,
            "T": e.temperature_kev,
            "n": e.density_m3,
            "tau": e.confinement_time_s,
            "nTau": e.lawson_parameter,
            "triple": e.triple_product,
        }
        for e in load_experiments()
    ]


def scenario_payload(s):
    return {
        "density": s.density,
        "heating": s.heating_power,
        "hFactor": s.h_factor,
        "densityPeaking": s.density_peaking,
        "temperaturePeaking": s.temperature_peaking,
        "radiationFactor": s.radiation_factor,
        "tritiumFraction": s.composition.tritium_fraction,
        "impurities": [list(pair) for pair in s.composition.impurities],
    }


def machine_payload(m):
    return {"R": m.major_radius, "a": m.minor_radius, "kappa": m.elongation, "delta": m.triangularity,
            "B": m.field, "I": m.current}


def write_data_js():
    payload = {
        "experiments": experiments_payload(),
        "machines": [
            {"name": n, "R": r, "a": a, "B": b, "I": i, "kappaSep": k, "deltaSep": d, "heatingMax": h}
            for n, r, a, b, i, k, d, h in MACHINES
        ],
        "presets": {
            "sparc": {"machine": machine_payload(reactor.SPARC), "scenario": scenario_payload(reactor.SPARC_SCENARIO),
                      "published": reactor.SPARC_PUBLISHED},
            "iter": {"machine": machine_payload(reactor.ITER), "scenario": scenario_payload(reactor.ITER_SCENARIO),
                     "published": reactor.ITER_PUBLISHED},
        },
        "publishedThresholds": {
            "idealIgnitionTemperature": 4.3,
            "lawsonQ1": [2.5e19, 26], "lawsonIgnition": [1.6e20, 26],
            "tripleQ1": [4.6e20, 14], "tripleIgnition": [2.9e21, 14],
        },
    }
    text = (
        "// Generated by tools/export_web_data.py. Do not edit by hand.\n"
        "// Experimental data: Wurzel & Hsu, Phys. Plasmas 32, 112106 (2025), Tables 1-3.\n"
        "// Machine parameters: Creely et al., J. Plasma Phys. 86, 865860502 (2020), Table 1.\n"
        f"export const DATA = {json.dumps(payload, indent=1)};\n"
    )
    (DOCS / "js").mkdir(parents=True, exist_ok=True)
    report = ROOT / "report" / "report.pdf"
    if report.exists():
        (DOCS / "report.pdf").write_bytes(report.read_bytes())
    (DOCS / "js" / "data.js").write_text(text, encoding="utf-8")


def write_vectors():
    rng = random.Random(20261113)
    plasmas = [
        (0.5, 0.0, 0.0, 6), (0.5, 0.05, 0.0, 6), (0.5, 0.10, 0.01, 6), (0.4, 0.0, 0.0, 6),
        (0.5, 0.0, 0.005, 10), (0.35, 0.08, 0.01, 4),
    ]
    lawson_cases = []
    for x, f_he, f_z, z in plasmas:
        plasma = lw.Plasma(tritium_fraction=x, helium_fraction=f_he, impurity_fraction=f_z, impurity_charge=z)
        impurities = [[2, f_he], [z, f_z]]
        for q in (1.0, 5.0, math.inf):
            for t in (3.0, 6.0, 14.2, 25.0, 60.0):
                lawson_cases.append({
                    "tritium": x, "impurities": impurities, "q": finite(q), "T": t,
                    "lawson": finite(float(lw.lawson_parameter(t, q, plasma))),
                    "lawsonNoBrems": finite(float(lw.lawson_parameter(t, q, plasma, bremsstrahlung=False))),
                })
    minima = []
    for x, f_he, f_z, z in plasmas:
        plasma = lw.Plasma(tritium_fraction=x, helium_fraction=f_he, impurity_fraction=f_z, impurity_charge=z)
        for q in (1.0, 10.0, math.inf):
            t_l, v_l = lw.minimum_lawson_parameter(q, plasma)
            t_t, v_t = lw.minimum_triple_product(q, plasma)
            minima.append({
                "tritium": x, "impurities": [[2, f_he], [z, f_z]], "q": finite(q),
                "lawson": [t_l, v_l], "triple": [t_t, v_t],
                "idealIgnition": finite(float(lw.ideal_ignition_temperature(plasma))),
            })
    gains = []
    for t, n_tau in ((18.6, 3.3e19), (28.0, 1.7e19), (11.0, 2.0e19), (20.0, 3.7e20), (5.0, 1e19), (3.0, 1e21)):
        gains.append({"T": t, "nTau": n_tau, "gain": finite(lw.q_fuel_from_state(t, n_tau))})

    reactor_cases = [(reactor.SPARC, reactor.SPARC_SCENARIO), (reactor.ITER, reactor.ITER_SCENARIO)]
    reactor_cases.append((reactor.SPARC, dataclasses.replace(reactor.SPARC_SCENARIO, h_factor=0.7)))
    reactor_cases.append((reactor.ITER, dataclasses.replace(reactor.ITER_SCENARIO, temperature_peaking=2.5)))
    reactor_cases.append((reactor.ITER, dataclasses.replace(reactor.ITER_SCENARIO, heating_power=0.0)))
    reactor_cases.append((reactor.SPARC, dataclasses.replace(reactor.SPARC_SCENARIO, heating_power=0.0)))
    big = reactor.Tokamak(6.0, 6.0 / 3.25, 1.75, 0.45, 12.0, 1.0).with_q95(3.62)
    for heating in (12.8, 2.0):
        reactor_cases.append((big, reactor.Scenario(
            density=0.37 * big.greenwald_density, heating_power=heating, density_peaking=1.4,
            temperature_peaking=2.5, radiation_factor=2.25, composition=reactor.SPARC_SCENARIO.composition)))
    for _ in range(40):
        r = rng.uniform(0.8, 9.0)
        machine = reactor.Tokamak(
            major_radius=r, minor_radius=r / rng.uniform(2.4, 4.5), elongation=rng.uniform(1.2, 2.0),
            triangularity=rng.uniform(0.0, 0.6), field=rng.uniform(1.5, 13.0), current=1.0,
        ).with_q95(rng.uniform(2.6, 5.0))
        scenario = reactor.Scenario(
            density=rng.uniform(0.25, 0.95) * machine.greenwald_density,
            heating_power=rng.choice([0.0, rng.uniform(2.0, 80.0)]),
            h_factor=rng.uniform(0.7, 1.3),
            density_peaking=rng.uniform(1.0, 1.6),
            temperature_peaking=rng.uniform(1.4, 3.0),
            radiation_factor=rng.uniform(1.0, 2.5),
            composition=reactor.Composition(
                tritium_fraction=rng.uniform(0.3, 0.7),
                impurities=((2, rng.uniform(0.0, 0.08)), (rng.choice([4, 6, 8, 10]), rng.uniform(0.0, 0.01))),
            ),
        )
        reactor_cases.append((machine, scenario))
    reactor_payload = []
    for machine, scenario in reactor_cases:
        result = reactor.solve(machine, scenario)
        reactor_payload.append({
            "machine": machine_payload(machine),
            "scenario": scenario_payload(scenario),
            "result": {
                "status": result.status,
                "centralTemperature": finite(result.central_temperature),
                "fusionPower": result.fusion_power,
                "radiatedPower": result.radiated_power,
                "lossPower": result.loss_power,
                "gain": finite(result.gain),
                "confinementTime": finite(result.confinement_time),
                "storedEnergy": result.stored_energy,
                "betaNormalised": result.beta_normalised,
                "q95": result.q95,
                "greenwaldFraction": result.greenwald_fraction,
                "lhThreshold": result.lh_threshold,
                "tripleProduct": finite(result.triple_product),
                "volume": result.volume,
                "surface": result.surface_area,
                "ignitionPossible": result.ignition_possible,
                "radiationBarrier": result.radiation_barrier,
            },
        })

    vectors = {
        "reactivity": [[t, float(lw.reactivity_dt(t))] for t in (0.2, 0.5, 1, 2, 5, 10, 14.2, 20, 30, 50, 66.6, 100)],
        "lawson": lawson_cases,
        "minima": minima,
        "gains": gains,
        "laser": [[t, float(lw.icf_ignition_lawson_parameter(t))] for t in (2.0, 4.5, 5.5, 10.9, 30.0)],
        "lineAverage": [[p, reactor.line_average_factor(p)] for p in (1.0, 1.05, 1.3, 1.4, 2.0, 2.7)],
        "reactor": reactor_payload,
    }
    (DOCS / "tests").mkdir(parents=True, exist_ok=True)
    (DOCS / "tests" / "vectors.json").write_text(json.dumps(vectors, indent=1), encoding="utf-8")
    return len(lawson_cases), len(minima), len(reactor_payload)


if __name__ == "__main__":
    write_data_js()
    counts = write_vectors()
    print(f"Wrote docs/js/data.js and docs/tests/vectors.json ({counts[0]} Lawson, {counts[1]} minima, {counts[2]} reactor cases)")
